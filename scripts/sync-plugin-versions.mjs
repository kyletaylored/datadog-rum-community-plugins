#!/usr/bin/env node
/**
 * Copies each plugin's package.json version into the three places that repeat it:
 *
 *   plugin.json                       `version`, which the site's pinned CDN snippets use
 *   src/index.ts                      `PLUGIN_VERSION`, sent on every event as commerce.plugin_version
 *   fixtures/.generated/events.json   the same attribute, as the fixture run recorded it
 *
 * `changeset version` bumps package.json only, so the release PR runs this straight after it
 * (`npm run version-packages`). Without it the 0.2.0 release PR shipped every plugin.json at
 * 0.1.0, which failed lint:manifests on main and blocked the publish.
 *
 * events.json is generated by the fixture run, and CI compares it against a fresh run, so the
 * edit here is checked rather than trusted: if it ever disagrees with what the plugin sends, CI
 * fails.
 *
 *   node scripts/sync-plugin-versions.mjs
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { relative } from 'node:path'
import { fromRoot, repoRoot } from './repo-root.mjs'

const VERSION_CONSTANT = /export const PLUGIN_VERSION = '[^']*'/
const VERSION_ATTRIBUTE = /("commerce\.plugin_version": )"[^"]*"/g
// Edits the one field in place rather than re-serializing, so the rest of a hand-written
// manifest (key order, \u escapes) stays exactly as its author left it.
const MANIFEST_VERSION = /^(  "version": )"[^"]*"/m

let changed = 0

function update(path, next) {
  const current = readFileSync(path, 'utf8')
  if (current === next) return
  writeFileSync(path, next)
  console.log(`updated ${relative(repoRoot, path)}`)
  changed += 1
}

for (const dir of readdirSync(fromRoot('packages')).sort()) {
  const manifestPath = fromRoot('packages', dir, 'plugin.json')
  if (!existsSync(manifestPath)) continue

  const { version } = JSON.parse(readFileSync(fromRoot('packages', dir, 'package.json'), 'utf8'))

  const manifest = readFileSync(manifestPath, 'utf8')
  if (!MANIFEST_VERSION.test(manifest)) {
    console.error(`${relative(repoRoot, manifestPath)}: no top-level "version" to update`)
    process.exit(1)
  }
  update(manifestPath, manifest.replace(MANIFEST_VERSION, `$1"${version}"`))

  const entry = fromRoot('packages', dir, 'src/index.ts')
  const source = readFileSync(entry, 'utf8')
  if (!VERSION_CONSTANT.test(source)) {
    console.error(`${relative(repoRoot, entry)}: no \`export const PLUGIN_VERSION = '…'\` to update — has it moved?`)
    process.exit(1)
  }
  update(entry, source.replace(VERSION_CONSTANT, `export const PLUGIN_VERSION = '${version}'`))

  const report = fromRoot('packages', dir, 'fixtures/.generated/events.json')
  if (existsSync(report)) {
    update(report, readFileSync(report, 'utf8').replace(VERSION_ATTRIBUTE, `$1"${version}"`))
  }
}

console.log(changed === 0 ? 'plugin versions already in sync' : `${changed} file(s) updated`)
